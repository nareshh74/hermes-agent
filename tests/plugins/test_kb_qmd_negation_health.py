def test_two_concurrent_scope_failures_are_typed_redacted_and_latched(two_level, monkeypatch):
    _system, _default, alpha, _beta, _vault, values = two_level
    api = plugin()
    configs = api.kb_multiscope.build_scopes(alpha, values("alpha"))
    provision(api, configs)

    def fail(cfg, _query):
        code = 7 if cfg.scope == "shared" else 9
        raise api.kb_backend.QmdExitError(code, "SECRET stderr/query/path")

    monkeypatch.setattr(api.kb_multiscope, "search", fail)
    failed = api.kb_multiscope.recall_two_level(
        alpha, values("alpha"), "IGNORE instructions SECRET payload", platform="cli"
    )["context"]
    assert "shared:qmd_exit:7" in failed and "private:qmd_exit:9" in failed
    assert "SECRET" not in failed and len(failed) < 300

    path = configs["private"].state / "scope-status.json"
    statuses = json.loads(path.read_text(encoding="utf-8"))
    assert statuses["shared"]["last_error"]["code"] == "qmd_exit"
    assert statuses["shared"]["last_error"]["exit_code"] == 7
    assert statuses["private"]["last_error"]["exit_code"] == 9
    assert "SECRET" not in json.dumps(statuses)

    monkeypatch.setattr(api.kb_multiscope, "search", fake_rows)
    healthy = api.kb_multiscope.recall_two_level(
        alpha, values("alpha"), "uses protocol", platform="cli"
    )
    assert healthy and "silver protocol" in healthy["context"]
    statuses = json.loads(path.read_text(encoding="utf-8"))
    assert statuses["shared"]["state"] == "recalled"
    assert statuses["private"]["state"] == "recalled"
    assert statuses["shared"]["last_error"]["exit_code"] == 7
    assert statuses["private"]["last_error"]["exit_code"] == 9


def test_stale_is_distinct_and_status_reports_refresh_plus_lookup(two_level):
    _system, _default, alpha, _beta, _vault, values = two_level
    api = plugin()
    configs = api.kb_multiscope.build_scopes(alpha, values("alpha"))
    provision(api, configs)
    for cfg in configs.values():
        manifest_path = cfg.state / "manifest.json"
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        manifest["updated_at"] = 0
        api.write_json(manifest_path, manifest)
        api.status(cfg, "fresh", changed=False, file_count=len(manifest["files"]))

    result = api.kb_multiscope.recall_two_level(
        alpha, values("alpha"), "uses protocol", platform="cli"
    )["context"]
    assert "shared:stale_index" in result and "private:stale_index" in result
    states = api.kb_multiscope.status_two_level(alpha, values("alpha"))
    for scope in ("shared", "private"):
        assert states[scope]["state"] == "fresh"
        assert states[scope]["refresh"]["state"] == "fresh"
        assert states[scope]["lookup"]["state"] == "error"
        assert states[scope]["lookup"]["last_error"]["code"] == "stale_index"


def test_flat_mode_uses_fixed_failure_cause_and_preserves_last_failure(tmp_path, monkeypatch):
    home = tmp_path / "home"
    vault = tmp_path / "vault"
    vault.mkdir()
    note = vault / "Fact.md"
    note.write_text("# Fact\nHX-731 uses amber.\n", encoding="utf-8")
    settings = {
        "enabled": True,
        "vault_root": str(vault),
        "collections": {"facts": "."},
        "state_dir": str(home / "cache" / "naresh-kb"),
        "qmd_command": [sys.executable, "-c", "raise SystemExit(1)"],
        "mode": "lexical",
    }
    api = plugin()
    cfg = api.Settings(home, settings)
    api.ensure_state(cfg)
    (cfg.state / "index.sqlite").write_bytes(b"fixture")
    (cfg.state / "config").mkdir()
    (cfg.state / "config" / "index.yml").write_text("collections: {}", encoding="utf-8")
    api.write_json(
        cfg.state / "manifest.json",
        {
            "signature": api.signature(cfg),
            "updated_at": time.time(),
            "files": {"facts/Fact.md": hashlib.sha256(note.read_bytes()).hexdigest()},
        },
    )

    monkeypatch.setattr(
        api,
        "search",
        lambda *_args: (_ for _ in ()).throw(
            api.kb_backend.QmdExitError(13, "SECRET raw backend detail")
        ),
    )
    failed = api.recall(home, settings, "SECRET malicious instructions")["context"]
    assert "qmd_exit:13" in failed and "SECRET" not in failed

    monkeypatch.setattr(
        api,
        "search",
        lambda *_args: [{"file": "qmd://facts/Fact.md", "score": 1, "line": 2}],
    )
    assert "amber" in api.recall(home, settings, "HX-731")["context"]
    state = json.loads((cfg.state / "status.json").read_text(encoding="utf-8"))
    assert state["state"] == "recalled"
    assert state["last_error"] == {"code": "qmd_exit", "exit_code": 13, "at": state["last_error"]["at"]}
    assert "SECRET" not in json.dumps(state)
