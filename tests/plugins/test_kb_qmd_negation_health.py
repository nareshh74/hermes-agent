def _semantic_clauses(args: list[str]) -> list[str]:
    if not args or args[0] != "query":
        return []
    return [line[5:] for line in args[1].splitlines() if line.startswith("vec: ")]


def _real_qmd_semantic_errors(
    queries: list[str], fixture: QmdFixture,
) -> list[str | None]:
    script = (
        "import {validateSemanticQuery} from " + json.dumps(fixture.store.as_uri()) + ";"
        "const q=JSON.parse(Bun.env.QMD_TEST_QUERIES);"
        "console.log(JSON.stringify(q.map(validateSemanticQuery)));"
    )
    result = subprocess.run(
        [fixture.bun, "-e", script],
        env={"QMD_TEST_QUERIES": json.dumps(queries)},
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=10,
        check=False,
    )
    assert result.returncode == 0, result.stderr
    return json.loads(result.stdout)


