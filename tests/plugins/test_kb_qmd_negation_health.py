@pytest.mark.parametrize(
    ("query", "retained"),
    [
        ("-p", "p"),
        ("--model", "model"),
        ("-term", "term"),
        ('-"quoted"', "quoted"),
        ("prefix\t-p", "p"),
        ("prefix\n--model", "model"),
        ("prefix\u00a0-term", "term"),
        ("prefix\u2003-term", "term"),
    ],
)
def test_semantic_negative_operator_routes_to_safe_quoted_lexical(hybrid_cfg, query, retained):
    args = plugin().kb_backend.search_args(hybrid_cfg, query)
    assert args[0] == "search"
    assert retained in args[1]
    assert "\n" not in args[1]
    assert all(part.startswith('"') and part.endswith('"') for part in args[1].split())
    assert _semantic_clauses(args) == []


def test_exact_notification_routes_lexical_while_internal_hyphens_stay_semantic(hybrid_cfg):
    api = plugin().kb_backend
    exact = api.search_args(hybrid_cfg, EXACT_NOTIFICATION)
    assert exact[0] == "search"
    safe_queries = ["real-time coordination", "write-ahead logging", "co-op protocol"]
    semantic = [api.search_args(hybrid_cfg, query) for query in safe_queries]
    assert all(args[0] == "query" for args in semantic)
    assert [clause for args in semantic for clause in _semantic_clauses(args)]


def test_real_qmd_accepts_emitted_safe_semantic_clauses(hybrid_cfg):
    fixture = require_qmd_fixture(require_store=True)
    api = plugin().kb_backend
    safe_queries = ["real-time coordination", "write-ahead logging", "co-op protocol"]
